"""Render committed benchmark results as Markdown tables (docs/design.md 8.5).

The JSON is the record; this is a view of it, regenerated rather than edited.

**Gap** is how far a solver's objective sits above the proven optimum, as a fraction of the
optimum's routing cost -- the objective less the penalty for riders nobody can seat. In a
seat-short event every solver pays that penalty for the same riders, and leaving it in the
denominator would shrink every gap by an order of magnitude. A solver that strands a rider the
optimum seats still shows the full penalty in its gap, which is the right size for that mistake.
"""

from __future__ import annotations

import statistics
from collections import defaultdict
from collections.abc import Callable, Iterable
from typing import Any

Record = dict[str, Any]
Key = tuple[Any, ...]


def _by_case(runs: Iterable[Record]) -> dict[Key, dict[str, Record]]:
    cases: dict[Key, dict[str, Record]] = defaultdict(dict)
    for run in runs:
        key = (run["n"], run["driver_ratio"], run["distribution"], run["seed"])
        cases[key][run["solver"]] = run
    return cases


def gap(record: Record, optimum: Record) -> float:
    return float(record["objective"] - optimum["objective"]) / float(optimum["routing_cost"])


def _pct(value: float) -> str:
    return f"{100 * value:.2f}%"


def _seconds(value: float) -> str:
    return f"{value:.1f} s" if value >= 1 else f"{1000 * value:.0f} ms"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def _grouped(
    cases: dict[Key, dict[str, Record]], key: Callable[[Key], Key]
) -> dict[Key, list[dict[str, Record]]]:
    groups: dict[Key, list[dict[str, Record]]] = defaultdict(list)
    for case, solved in sorted(cases.items()):
        groups[key(case)].append(solved)
    return groups


def _gap_rows(groups: dict[Key, list[dict[str, Record]]]) -> list[list[str]]:
    rows = []
    for label, cases in groups.items():
        attempted = [c for c in cases if "exact" in c]
        proven = [c for c in attempted if c["exact"]["optimal"]]
        if not proven:
            continue
        greedy_gaps = [gap(c["greedy"], c["exact"]) for c in proven]
        lns_gaps = [gap(c["lns"], c["exact"]) for c in proven]
        rows.append(
            [
                *(str(part) for part in label),
                f"{len(proven)}/{len(attempted)}",
                _pct(statistics.mean(greedy_gaps)),
                _pct(max(greedy_gaps)),
                _pct(statistics.mean(lns_gaps)),
                _pct(max(lns_gaps)),
                f"{sum(1 for g in lns_gaps if g < 1e-9)}/{len(proven)}",
                _seconds(statistics.median(c["exact"]["seconds"] for c in proven)),
                _seconds(max(c["exact"]["seconds"] for c in proven)),
            ]
        )
    return rows


def render(results: dict[str, Any]) -> str:
    env = results["environment"]
    cases = _by_case(results["runs"])
    gap_header = [
        "proven",
        "greedy mean",
        "greedy max",
        "LNS mean",
        "LNS max",
        "LNS optimal",
        "CP-SAT median",
        "CP-SAT max",
    ]

    lines = [
        "# Benchmarks",
        "",
        "Generated by `make bench-report` from [`results.json`](results.json); do not edit by "
        "hand. Regenerate the results with `make bench`. Methodology: `docs/design.md` §8.5 and "
        "`packages/bench/`.",
        "",
        f"Ran on {env['system']} {env['machine']}, Python {env['python']}, OR-Tools "
        f"{env['ortools']}. LNS ran as production runs it: greedy, then search, inside a "
        f"{env['lns_budget_seconds']:g} s wall-clock budget (at most {env['lns_max_iterations']:,}"
        " iterations). The exact model is set partitioning on CP-SAT, given LNS's answer as a hint"
        f" and {env['exact_time_limit_seconds']:g} s to prove it, for every instance up to "
        f"n = {env['exact_max_n']}.",
        "",
        "Every instance is synthetic (`generate_instance`, haversine travel times, no flexible "
        "drivers). These are not measurements of real events.",
        "",
        "## Gap to the proven optimum",
        "",
        "Gap is the objective above the optimum as a fraction of the optimum's routing cost (the "
        "objective less the unassigned penalty, which in a seat-short event every solver pays for "
        "the same riders). *LNS optimal* counts instances where LNS found the optimum.",
        "",
    ]
    lines += _table(
        ["n", "driver ratio", *gap_header],
        _gap_rows(_grouped(cases, lambda k: (k[0], k[1]))),
    )
    lines += ["", "### By spatial distribution", ""]
    lines += _table(
        ["distribution", *gap_header],
        _gap_rows(_grouped(cases, lambda k: (k[2],))),
    )

    lines += [
        "",
        "## LNS against greedy, at every size",
        "",
        "Improvement is the fall in routing cost from greedy's answer to LNS's.",
        "",
    ]
    rows = []
    for (n, ratio), group in _grouped(cases, lambda k: (k[0], k[1])).items():
        improvements = [
            (c["greedy"]["routing_cost"] - c["lns"]["routing_cost"]) / c["greedy"]["routing_cost"]
            for c in group
        ]
        rows.append(
            [
                str(n),
                str(ratio),
                str(len(group)),
                _pct(statistics.mean(improvements)),
                _seconds(statistics.median(c["greedy"]["seconds"] for c in group)),
                _seconds(statistics.median(c["lns"]["seconds"] for c in group)),
                f"{statistics.median(c['lns']['iterations'] for c in group):,.0f}",
                f"{statistics.mean(c['lns']['unassigned'] for c in group):.1f}",
                f"{statistics.mean(c['greedy']['p95_detour_s'] for c in group):.0f} s",
                f"{statistics.mean(c['lns']['p95_detour_s'] for c in group):.0f} s",
            ]
        )
    lines += _table(
        [
            "n",
            "driver ratio",
            "instances",
            "LNS improvement",
            "greedy time",
            "LNS time",
            "LNS iterations",
            "unassigned",
            "greedy p95 detour",
            "LNS p95 detour",
        ],
        rows,
    )
    return "\n".join(lines) + "\n"
